const languageControl = `
    <details class="language-switcher">
        <summary data-i18n-aria-label="language.change">
            <svg aria-hidden="true" viewBox="0 0 24 24" focusable="false"><circle cx="12" cy="12" r="8.5"></circle><path d="M3.5 12h17M12 3.5c2.3 2.4 3.5 5.2 3.5 8.5S14.3 18.1 12 20.5C9.7 18.1 8.5 15.3 8.5 12S9.7 5.9 12 3.5Z"></path></svg>
            <span class="language-current">EN</span>
        </summary>
        <div class="language-menu" role="group" data-i18n-aria-label="language.change">
            <button type="button" data-language-option="en" lang="en" data-i18n="language.english">English</button>
            <button type="button" data-language-option="ko" lang="ko" data-i18n="language.korean">한국어</button>
        </div>
    </details>`;

function getPreferredLanguage() {
    const savedLanguage = localStorage.getItem('site-language');
    return savedLanguage === 'ko' ? 'ko' : 'en';
}

function translate(key, language = getPreferredLanguage()) {
    return translations[language]?.[key] ?? translations.en[key] ?? key;
}

function applyLanguage(language) {
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach((element) => {
        element.innerHTML = translate(element.dataset.i18n, language);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
        element.setAttribute('aria-label', translate(element.dataset.i18nAriaLabel, language));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((element) => {
        element.setAttribute('title', translate(element.dataset.i18nTitle, language));
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
        element.setAttribute('alt', translate(element.dataset.i18nAlt, language));
    });
    document.querySelectorAll('[data-i18n-content]').forEach((element) => {
        element.setAttribute('content', translate(element.dataset.i18nContent, language));
    });
    document.title = translate(document.documentElement.dataset.i18nTitle, language);
    document.querySelectorAll('.language-current').forEach((element) => {
        element.textContent = language === 'ko' ? '한국어' : 'EN';
    });
    document.querySelectorAll('[data-language-option]').forEach((button) => {
        button.setAttribute('aria-pressed', String(button.dataset.languageOption === language));
    });
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
}

function initializeLanguage() {
    document.querySelectorAll('[data-language-control]').forEach((container) => {
        container.innerHTML = languageControl;
    });
    document.addEventListener('click', (event) => {
        const option = event.target.closest('[data-language-option]');
        if (!option) return;

        const language = option.dataset.languageOption;
        localStorage.setItem('site-language', language);
        applyLanguage(language);
        option.closest('.language-switcher').removeAttribute('open');
    });
    applyLanguage(getPreferredLanguage());
}

window.siteI18n = { getPreferredLanguage, translate };
document.addEventListener('DOMContentLoaded', initializeLanguage);
